-- Lua脚本运行时自动管理以下生命周期函数：
--   • initial()  - 脚本首次被调用时执行一次（懒加载）
--   • MainProcess() - 每次规则触发时调用（如果存在）
--   • dispose() - Mod卸载时执行一次
--
-- 这种设计模式确保：
--   1. 资源初始化只进行一次，避免重复分配
--   2. 脚本全局状态在多次调用间保持
--   3. Mod卸载时能够妥善清理和保存资源
--

--- ============================================================================
--- initial() 函数 - 脚本初始化函数
--- ============================================================================
---
--- 【调用时机】脚本首次被执行时自动调用（且仅调用一次）
---
--- 【主要职责】
---   1. 初始化全局状态变量（缓存、标志位等）
---   2. 加载持久化数据到内存中（可选）
---   3. 向 _script_registry 注册 API 接口供其他脚本使用
---   4. 初始化所需的常量、数据结构等
---
--- 【最佳实践】
---   ✓ 在此函数中初始化所有全局变量（_G.xxx）
---   ✓ 在此函数中导出 API 到 _script_registry
---   ✓ 避免在此处执行复杂计算或阻塞操作
---   ✗ 不要在此处读取用户特定的数据，应在 MainProcess 中读取
---   ✗ 不要在此处执行业务逻辑，应在专用函数中执行
---
--- 【示例架构】
---   initial() 
---     -> _G.affinity_cache = {}        (初始化本地缓存字典)
---     -> _G.cache_dirty = false        (初始化脏标志)
---     -> _script_registry["feedpet"] = {...}  (注册导出API)
---
function initial()
    -- ========================================================================
    -- 1. 初始化本地缓存表结构
    -- ========================================================================
    -- 目的：在内存中维护一个用户好感度的本地缓存
    -- 优势：
    --   • 避免频繁访问持久化存储（IO操作较慢）
    --   • 提高查询速度
    --   • 在 dispose() 中批量保存所有改动
    --
    -- 缓存表格式：
    --   _G.affinity_cache = {
    --       ["用户ID1"] = 好感度值,
    --       ["用户ID2"] = 好感度值,
    --       ...
    --   }
    --
    _G.affinity_cache = {}
    
    -- 标志位：标记缓存中是否有未保存的改动
    -- dispose() 中会根据此标志决定是否需要保存数据
    -- 这样可以优化性能：只有数据改动时才执行保存操作
    _G.cache_dirty = false
    
    -- ========================================================================
    -- 2. 从持久化存储加载已有的好感度数据到缓存
    -- ========================================================================
    -- 目的：在脚本初始化时恢复上一次运行的所有用户好感度数据
    -- 这样可以实现"热启动"，减少首次查询时的延迟
    --
    -- 注意：这是一个演示模式。实际应用中，如果用户数量很大（>1000），
    -- 建议改为"冷加载"：按需加载每个用户的数据
    --
    
    -- 扫描所有可能的存储键（这里使用模式匹配）
    -- 注：实际环境中可能需要通过某种方式获取所有已保存的用户ID
    -- 本演示假设之前保存过的键格式为: "cache_{用户ID}"
    --
    -- 【重要】这是一个模型演示函数，展示如何从存储加载数据
    -- 在实际应用中，应根据具体的存储API来实现此功能
    
    -- 示例：如果你有一个函数可以获取所有存储键
    -- 下面是伪代码演示如何加载：
    --   local stored_keys = mod_storage_get_all_keys()  -- 伪函数
    --   for _, key in ipairs(stored_keys) do
    --       if string.match(key, "^cache_") then
    --           local uid = string.sub(key, 7)  -- 提取用户ID
    --           local value = mod_storage_read(key)
    --           _G.affinity_cache[uid] = tonumber(value) or 100
    --       end
    --   end
    
    -- ========================================================================
    -- 3. 初始化脚本元数据表
    -- ========================================================================
    -- 存储脚本相关的元数据（可选）
    -- 用途：记录脚本运行时的统计信息、配置等
    --
    _G.script_metadata = {
        version = "1.0.0",              -- 脚本版本
        initialized_at = os.time(),     -- 初始化时间戳
        total_users_cached = 0,         -- 缓存的用户总数
        last_save_time = 0              -- 最后一次保存的时间
    }
    
    -- ========================================================================
    -- 4. 向全局脚本注册表导出接口
    -- ========================================================================
    -- _script_registry 是一个全局表，存储所有脚本导出的API
    -- 其他脚本可以通过 get_script("feedpet") 来获取这些接口
    --
    -- 格式：_script_registry["脚本名"] = { 函数名1 = 函数引用, 函数名2 = 函数引用, ... }
    --
    -- 导出的 API 将被用于：
    --   • 其他脚本调用本脚本的功能
    --   • 跨脚本间的数据共享
    --   • 实现模块化的脚本架构
    --
    _script_registry["feedpet"] = {
        -- 获取指定好感度对应的等级信息和回复内容
        get_affinity = GetAffinityInfo,
        
        -- 查询用户当前的好感度
        query_affinity = QueryAffinity,
        
        -- 获取根据好感度生成的对话内容
        talk_to_bot = TalkToBot,
        
        -- 【演示】导出缓存相关的函数供外部使用
