--- ============================================================================
--- MainProcess() 函数 - 主处理函数（投喂功能）
--- ============================================================================
---
--- 【调用时机】
---   当规则被触发且配置使用此脚本时调用（每次都调用）
---   通过在规则的回复中使用 <func MainProcess()> 标签来调用
---
--- 【功能说明】
---   实现完整的投喂流程：
---   1. 读取用户当前的好感度
---   2. 生成随机增长值 (1-50)
---   3. 更新并保存新的好感度
---   4. 获取好感度对应的等级反应
---   5. 返回格式化的结果消息
---
--- 【返回值】
---   返回一个格式化的字符串，包含：
---   • 增加的好感度数值
---   • 当前的好感度总数
---   • 等级反应
---
--- 【参数访问】
---   此函数可以访问以下全局变量（由运行时注入）：
---   • user_id: 当前用户的 QQ 号（数字）
---   • group_id: 所在群组的 ID（数字）
---   • message: 原始消息内容（字符串）
---
--- 【错误容错】
---   • 如果用户数据不存在，初始化为 100 点
---   • 如果好感度超过上限，自动限制到 500
---   • 如果没有匹配的等级，返回最后一个等级的回复
---
function MainProcess()
    -- ========================================================================
    -- 步骤 1：获取用户标识并初始化随机数生成
    -- ========================================================================
    -- 将用户ID转换为字符串，用作数据存储的键
    local current_user_id = tostring(user_id)
    
    -- 使用当前时间加用户ID的组合作为随机种子
    -- 这样可以确保每次调用都生成不同的随机数
    -- % 1000 是为了避免种子数字太大
    math.randomseed(os.time() + tonumber(current_user_id) % 1000)
    
    -- 生成 1 到 50 之间的随机好感度增长值
    -- 这样可以增加游戏的不确定性，玩家每次投喂的收益都不同
    local growth_value = math.random(1, 50)
    
    -- ========================================================================
    -- 步骤 2：从持久化存储读取当前好感度
    -- ========================================================================
    -- 构建存储键：使用用户ID来唯一标识每个用户的数据
    local store_key = "bot_affinity_" .. current_user_id
    
    -- 从 Mod Storage 读取好感度数据
    -- 如果键不存在，mod_storage_read 返回 nil，此时默认为 100
    -- tonumber() 用于将字符串转换为数字，如果转换失败返回 nil
    local current_affinity = tonumber(mod_storage_read(store_key)) or 100
    
    -- ========================================================================
    -- 步骤 3：计算新的好感度并应用上限
    -- ========================================================================
    -- 将增长值加到当前好感度上
    local new_affinity = current_affinity + growth_value
    
    -- 限制好感度不超过 500（上限建议值）
    -- 这样可以避免数字变得过大，并给游戏增加一个"满足感"
    if new_affinity > 500 then
        new_affinity = 500
    end
    
    -- ========================================================================
    -- 步骤 4：保存新的好感度到持久化存储
    -- ========================================================================
    -- 使用 mod_storage_write 函数保存数据
    -- 注意：需要将数字转换为字符串再保存
    mod_storage_write(store_key, tostring(new_affinity))
    
    -- 标记缓存有改动，供 dispose() 函数在卸载时检查是否需要保存
    -- （虽然这里已经直接保存了，但如果使用缓存策略时需要设置此标志）
    _G.cache_dirty = true
    
    -- ========================================================================
    -- 步骤 5：获取好感度对应的等级信息和回复
    -- ========================================================================
    -- 调用 GetAffinityInfo() 函数获取新好感度对应的等级信息
    local affinity_info = GetAffinityInfo(new_affinity)
    
    -- ========================================================================
    -- 步骤 6：构建并返回格式化的结果消息
    -- ========================================================================
    -- 使用 string.format 格式化输出：
    --   • %d 整数占位符（好感度增长值）
    --   • %s 字符串占位符（好感度等级反应）
    -- \n 换行符用于排版
    local result = string.format(
        "哦，吃的！！\n增加了 %d 好感度\n当前好感度：%d/500\n\n%s",
        growth_value,
        new_affinity,
        affinity_info.response
    )
    
    -- 返回最终的消息，这将被插入到规则的回复中
    return result
end

--- ============================================================================
--- GetAffinityInfo() 函数 - 获取好感度等级信息
--- ============================================================================
---
--- 【功能说明】
---   根据好感度数值查找对应的等级配置，返回该等级的信息
---   这是一个通用的查询函数，被多个功能函数调用
---
--- 【参数】
---   affinity_value: 好感度数值（整数）
---
--- 【返回值】
---   返回一个 Lua 表，包含：
---   • response: 等级对应的回复字符串
---   • value: 好感度的原始数值
---
--- 【使用示例】
---   local info = GetAffinityInfo(150)
---   print(info.response)  -- 输出该等级的回复
---   print(info.value)     -- 输出 150
---
--- 【错误处理】
---   如果没有找到匹配的等级，返回 AFFINITY_LEVELS 中的最后一个等级
---   这确保函数总是返回有效的数据，避免 nil 引用错误
---
function GetAffinityInfo(affinity_value)
    -- 遍历所有定义的好感度等级
    for _, level in ipairs(AFFINITY_LEVELS) do
        -- 检查好感度是否在这个等级的范围内
        if affinity_value >= level.min and affinity_value <= level.max then
            -- 找到匹配的等级，返回其信息
            return {
                response = level.response,
                value = affinity_value
            }
        end
    end
    
    -- 如果没有匹配的等级（好感度超过所有定义的等级）
    -- 返回最后一个等级作为默认处理
    -- 这样无论好感度多高，始终能返回一个有效的响应
    local last_level = AFFINITY_LEVELS[#AFFINITY_LEVELS]
    return {
        response = last_level.response,
        value = affinity_value
    }
end

--- ============================================================================
--- QueryAffinity() 函数 - 查询用户的好感度
--- ============================================================================
---
--- 【功能说明】
---   查询当前用户的好感度，返回详细的好感度信息和百分比
---   用于实现"查询好感度"功能
---
--- 【返回值】
---   返回当前用户的好感度数值、百分比、等级反应
---   格式化为易读的字符串
---
--- 【使用场景】
---   用户想要查看当前的好感度状态时调用
---   通过规则 <func QueryAffinity()> 标签来使用
---
function QueryAffinity()
    -- 获取当前用户ID并从存储中读取好感度
    local current_user_id = tostring(user_id)
    local store_key = "bot_affinity_" .. current_user_id
    local current_affinity = tonumber(mod_storage_read(store_key)) or 100
    
    -- 获取好感度对应的等级信息
    local affinity_info = GetAffinityInfo(current_affinity)
    
    -- 计算好感度百分比（当前好感度 / 上限 * 100）
    local percentage = (current_affinity / 500) * 100
    
    -- 构建返回消息
    -- 注意：这里使用 \\n 是因为需要在字符串中表示 Lua 的转义字符
    local result = string.format(
        "%s 对我的好感度：%d/500 (%.0f%%)\\n\\n%s",
        current_affinity,
        percentage,
        affinity_info.response
    )
    
    return result
end

--- ============================================================================
--- TalkToBot() 函数 - 根据好感度生成对话
--- ============================================================================
---
--- 【功能说明】
---   根据用户的当前好感度，从对应等级的对话池中随机选择一条对话
---   实现"和我对话"的功能
---
--- 【返回值】
---   返回一条格式化的对话字符串
---
--- 【设计思想】
---   • 不同好感度等级有不同的对话集合
---   • 每次调用时从对话集中随机选择一条
---   • 增加交互的多样性和趣味性
---
--- 【使用场景】
---   用户触发"对话"或"聊天"相关规则时调用
---
function TalkToBot()
    -- 获取用户ID和当前好感度
    local current_user_id = tostring(user_id)
    local store_key = "bot_affinity_" .. current_user_id
    local current_affinity = tonumber(mod_storage_read(store_key)) or 100
    
    -- ========================================================================
    -- 步骤 1：根据好感度找到对应等级的对话池
    -- ========================================================================
    local dialog_pool = nil
    
    -- 遍历所有等级，找到好感度对应的等级
    for _, level in ipairs(AFFINITY_LEVELS) do
        if current_affinity >= level.min and current_affinity <= level.max then
            -- 如果这个等级有对话集（conversations 数组非空）
            if level.conversations and #level.conversations > 0 then
                dialog_pool = level.conversations
            else
                -- 如果没有对话集，使用等级的回复内容作为对话
                dialog_pool = { level.response }
            end
            break
        end
    end
    
    -- ========================================================================
    -- 步骤 2：容错处理 - 如果没有找到匹配的等级
    -- ========================================================================
    if not dialog_pool then
        -- 使用最后一个等级的内容
        local last_level = AFFINITY_LEVELS[#AFFINITY_LEVELS]
        if last_level.conversations and #last_level.conversations > 0 then
            dialog_pool = last_level.conversations
        else
            dialog_pool = { last_level.response }
        end
    end
    
    -- ========================================================================
    -- 步骤 3：从对话池中随机选择一条
    -- ========================================================================
    -- 初始化随机数生成器
    math.randomseed(os.time() + tonumber(current_user_id) % 1000)
    
    -- 生成 1 到对话池大小之间的随机索引
    local random_index = math.random(1, #dialog_pool)
    
    -- 根据随机索引获取对话内容
    local selected_dialog = dialog_pool[random_index]
    
    -- ========================================================================
    -- 步骤 4：返回选中的对话
    -- ========================================================================
    return selected_dialog
end

