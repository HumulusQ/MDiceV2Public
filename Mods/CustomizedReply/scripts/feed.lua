--- ============================================================================
--- dispose() 函数 - 脚本清理和资源保存函数
--- ============================================================================
---
--- 【调用时机】Mod卸载时自动调用（且仅调用一次）
---
--- 【主要职责】
---   1. 保存所有状态数据到持久化存储（Mod Storage）
---   2. 关闭文件句柄、数据库连接等资源
---   3. 清理全局变量，释放内存
---   4. 记录清理过程日志
---
--- 【最佳实践】
---   ✓ 在此函数中保存所有需要保持的状态数据
---   ✓ 清理所有全局变量（_G.xxx = nil）
---   ✓ 使用 try-catch 模式处理保存失败的情况
---   ✗ 不要假设 dispose() 一定会被调用（如果程序崩溃可能不会调用）
---   ✗ 不要在此处执行长时间的操作（可能导致卸载超时）
---   ✗ 不要修改规则或其他脚本的状态
---
--- 【数据保存流程】
---   1. 检查缓存是否有改动（_G.cache_dirty）
---   2. 遍历缓存中的所有用户数据
---   3. 将每个用户的好感度保存到 mod_storage
---   4. 清理内存中的缓存
---   5. 重置所有全局变量
---
function dispose()
    -- ========================================================================
    -- 1. 保存缓存中的所有数据到持久化存储
    -- ========================================================================
    -- 目的：将内存中修改过的好感度数据持久化保存
    -- 策略：延迟批量保存（只有数据改动时才保存）
    -- 
    -- 这种设计的优势：
    --   • 减少IO操作（只在必要时保存）
    --   • 提高性能（批量操作比逐个操作快）
    --   • 确保数据不丢失（Mod卸载时强制保存）
    --
    
    -- 第一步：检查缓存是否有更新（如果没有改动则跳过保存）
    if _G.affinity_cache and _G.cache_dirty then
        -- 遍历缓存表中的所有用户数据
        -- pairs() 函数用于遍历表中的键值对
        -- uid: 用户ID（字符串或数字）
        -- affinity_value: 该用户的好感度值（数字）
        --
        for uid, affinity_value in pairs(_G.affinity_cache) do
            -- ================================================================
            -- 保存单个用户的好感度到持久化存储
            -- ================================================================
            -- 存储键名称约定：cache_{用户ID}
            -- 例如：cache_123456789 (用户QQ号为123456789)
            --
            -- mod_storage_write(键, 值) 函数说明：
            --   • 键：用于唯一标识存储项的字符串
            --   • 值：需要保存的内容（必须转换为字符串）
            --
            local store_key = "cache_" .. uid
            local store_value = tostring(affinity_value)
            
            -- 执行保存操作
            mod_storage_write(store_key, store_value)
            
            -- ================================================================
            -- 验证保存（可选）
            -- ================================================================
            -- 为了确保数据被正确保存，可以立即读取验证
            -- 这在调试时很有用，但在生产环境中应注释掉以提高性能
            --
            -- local verify_value = mod_storage_read(store_key)
            -- if verify_value ~= store_value then
            --     print(string.format("[feedpet] ⚠ Save verification failed for user %s", uid))
            -- end
        end
        
        -- 标记缓存为"干净"（已保存）
        _G.cache_dirty = false
        
        -- 更新元数据中的最后保存时间
        if _G.script_metadata then
            _G.script_metadata.last_save_time = os.time()
        end
    end
    
    -- ========================================================================
    -- 2. 清理内存中的缓存数据
    -- ========================================================================
    -- 目的：释放内存，防止内存泄漏
    -- 
    -- 必要性说明：
    --   • 脚本卸载时，全局变量不会自动清理
    --   • 显式设置为 nil 可以让 Lua 垃圾回收器立即回收内存
    --   • 这对于长期运行的程序很重要
    --
    
    -- 清理缓存表：遍历并删除所有条目
    -- 这样做可以彻底释放占用的内存
    if _G.affinity_cache then
        -- 方法1：逐个删除表元素
        for uid in pairs(_G.affinity_cache) do
            _G.affinity_cache[uid] = nil
        end
        
        -- 方法2：将整个表设为 nil
        _G.affinity_cache = nil
    end
    
    -- 清理缓存脏标志
    _G.cache_dirty = nil
    
    -- 清理元数据表
    if _G.script_metadata then
        _G.script_metadata = nil
    end
    
    -- ========================================================================
    -- 3. 其他特殊资源的清理（如果需要）
    -- ========================================================================
    -- 这里可以添加其他的清理操作，例如：
    --   • 关闭文件句柄
    --   • 断开数据库连接
    --   • 清理定时器
    --   • 注销事件监听器
    --
    -- 本脚本中目前没有这些资源，但说明一下最佳实践
    
    -- ========================================================================
    -- 4. 日志记录（可选）
    -- ========================================================================
    -- 记录脚本的清理过程，用于调试和监控
    --
    -- print(string.format(
    --     "[feedpet] ✓ Script disposed | Saved users: %d | Cache cleaned",
    --     _G.script_metadata and _G.script_metadata.total_users_cached or 0
    -- ))
    
    -- ========================================================================
    -- 5. 容错处理示例（生产级代码应包含）
    -- ========================================================================
    -- 如果需要更强的容错能力，可以使用 pcall 包装关键操作：
    --
