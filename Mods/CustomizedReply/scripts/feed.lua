--
-- 【核心功能】
--   1. 投喂：每次增加 1-50 的随机好感度值
--   2. 好感度等级系统：根据好感度值返回不同等级的回复
--   3. 持久化存储：使用 mod_storage_{read|write} 保存用户好感度数据
--   4. 跨脚本通信：通过 _script_registry 导出 API 供其他脚本使用
--   5. 动态对话池：不同好感度等级对应不同的对话内容
--
-- 【关键特性】
--   • 初始化模式（initial()）：首次调用时执行一次，初始化全局状态和缓存
--   • 清理模式（dispose()）：Mod卸载时执行一次，保存状态到持久化存储
--   • 数据持久化：好感度数据在本地缓存和持久存储之间同步
--   • 错误容错：默认好感度为100，不存在的用户自动初始化
--   • 最佳实践范例：展示如何正确使用 Lua 脚本特性
--
-- ============================================================================
-- 【使用示例】
--   • 规则1：投喂机器人
--     - 触发词：投喂|增加好感度|喂
--     - 脚本函数：<func MainProcess()>
--   • 规则2：查询好感度
--     - 触发词：好感度|查询好感度
--     - 脚本函数：<func QueryAffinity()>
--   • 规则3：和我对话
--     - 触发词：对话|聊天
--     - 脚本函数：<func TalkToBot()>
