    local affinity_value = tonumber(value) or 100
    
    -- 限制范围
    if affinity_value < 0 then affinity_value = 0 end
    if affinity_value > 500 then affinity_value = 500 end
    
    mod_storage_write(store_key, tostring(affinity_value))
    
    local affinity_info = GetAffinityInfo(affinity_value)
    return string.format("好感度已设置为 %d", affinity_value)
end

